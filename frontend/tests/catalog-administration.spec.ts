import { test, expect } from '@playwright/test'

test('administrator creates a draft, sees duplicate SKU and publishing diagnostics, edits parameters and changes sale status', async ({ page }) => {
  const username = process.env.BROWSER_ADMIN_USERNAME, password = process.env.BROWSER_ADMIN_PASSWORD
  if (!username || !password) throw new Error('Run with the isolated browser test administrator.')
  const sku = `WEB05-${Date.now()}`
  await page.goto('/#login')
  const login = page.getByRole('dialog', { name: '统一登录' })
  await login.getByLabel('用户名', { exact: true }).fill(username)
  await login.getByLabel('密码', { exact: true }).fill(password)
  await login.getByRole('button', { name: '登录', exact: true }).click()
  const admin = page.getByRole('dialog', { name: '管理后台' })
  await admin.getByRole('navigation').getByRole('button', { name: '商品管理' }).click()
  await admin.getByRole('button', { name: '新增商品' }).click()
  await admin.getByLabel('销售 SKU', { exact: true }).fill(sku)
  await admin.getByLabel('商品类别', { exact: true }).selectOption('PSU')
  await admin.getByLabel('商品名称', { exact: true }).fill('浏览器测试电源')
  await admin.getByLabel('初始售价（元）').fill('699.00')
  await admin.getByRole('button', { name: '保存草稿' }).click()
  await expect(admin.getByRole('status')).toContainText('保存成功')
  await expect(admin.getByLabel('销售 SKU', { exact: true })).toBeDisabled()
  await admin.getByRole('button', { name: '上架商品' }).click()
  await expect(admin.getByRole('alert')).toContainText('ratedPower')
  await admin.getByLabel('品牌', { exact: true }).fill('测试品牌')
  await admin.getByLabel('型号', { exact: true }).fill('Demo-750')
  await admin.getByLabel('摘要', { exact: true }).fill('750W 演示')
  await admin.getByLabel('描述', { exact: true }).fill('浏览器自动化验证专用电源')
  await admin.getByLabel('图片地址', { exact: true }).fill('/images/psu.svg')
  await admin.getByLabel('商品来源地址', { exact: true }).fill('https://example.com/psu')
  await admin.getByLabel('有效额定功率 · W', { exact: true }).fill('750')
  await admin.getByLabel('有效额定功率来源').fill('https://example.com/psu')
  await admin.getByRole('button', { name: '保存修改' }).click()
  await expect(admin.getByRole('status')).toContainText('保存成功')
  await admin.getByRole('button', { name: '上架商品' }).click()
  await expect(admin.getByRole('status')).toContainText('已上架')
  const publicResponse = await page.request.get(`/api/products?keyword=${sku}`)
  expect((await publicResponse.json()).data).toHaveLength(1)
  await admin.getByRole('button', { name: '下架商品' }).click()
  await expect(admin.getByRole('status')).toContainText('已下架')
  await page.screenshot({ path: '../.local/task-05-editor.png', fullPage: true, animations: 'disabled' })
  await admin.getByRole('button', { name: '返回商品列表' }).click()
  await admin.getByLabel('商品关键词').fill(sku)
  await admin.getByRole('button', { name: '查询', exact: true }).click()
  await expect(admin.getByRole('row').filter({ hasText: sku })).toContainText('已下架')
  await admin.getByRole('button', { name: '新增商品' }).click()
  await admin.getByLabel('销售 SKU', { exact: true }).fill(sku)
  await admin.getByRole('button', { name: '保存草稿' }).click()
  await expect(admin.getByRole('alert')).toContainText('SKU 已存在')
})

test('motherboard combinations remain readable publicly and administration filters expose typed existing parameters', async ({ page }) => {
  await page.goto('/')
  await page.locator('.product-card').filter({ hasText: 'B760M' }).getByRole('heading').getByRole('link').click()
  await expect(page.getByRole('dialog', { name: '商品详情' })).toContainText('M.2 2280 · PCIe · NVMe')
  await page.goto('/#login')
  const login = page.getByRole('dialog', { name: '统一登录' })
  await login.getByLabel('用户名', { exact: true }).fill(process.env.BROWSER_ADMIN_USERNAME!)
  await login.getByLabel('密码', { exact: true }).fill(process.env.BROWSER_ADMIN_PASSWORD!)
  await login.getByRole('button', { name: '登录', exact: true }).click()
  const admin = page.getByRole('dialog', { name: '管理后台' })
  await admin.getByRole('navigation').getByRole('button', { name: '商品管理' }).click()
  await admin.getByLabel('筛选商品类别').selectOption('MOTHERBOARD')
  await admin.getByLabel('商品关键词').fill('B760M')
  await admin.getByRole('button', { name: '查询', exact: true }).click()
  await expect(admin.getByRole('row').filter({ hasText: 'ASUS-TUF-B760M' })).toHaveCount(1)
  await admin.getByRole('button', { name: '查看编辑' }).click()
  await expect(admin.getByLabel('销售 SKU', { exact: true })).toBeDisabled()
  await expect(admin.getByLabel('商品类别', { exact: true })).toBeDisabled()
  await expect(admin.getByLabel('内存插槽数 · 个', { exact: true })).toHaveValue('4')
  await expect(admin.getByLabel('SSD规格3', { exact: true })).toHaveValue('M.2 2280')
  await admin.getByRole('button', { name: '返回商品列表' }).click()
  await page.screenshot({ path: '../.local/task-05-list.png', fullPage: true, animations: 'disabled' })
})
